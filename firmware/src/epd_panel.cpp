void EPD_READBUSY(void) {
  // Same predicate as Elecrow: wait while BUSY is LOW. Their comment says HIGH=busy, so
  // this waits for the waveform to *start*. A 5s cap avoids a hang if it never rises.
  const uint32_t t0 = millis();
  while (EPD_ReadBUSY == 0) {
    if (millis() - t0 > 5000) break;
    input::service();
    delay(1);
  }
}

void EPD_Update(uint32_t settleMs) {
  EPD_WR_REG(0x17);
  EPD_WR_DATA8(0xA5);
  // OEM returns when BUSY goes HIGH (waveform start). Count settle from the trigger so
  // DU is a steady ~300ms, not busy-time plus another 350ms.
  const uint32_t t0 = millis();
  EPD_READBUSY();
  while (millis() - t0 < settleMs) {
    input::service();
    delay(1);
  }
}

void EPD_HW_SW_RESET(void) {
  delay(100);
  EPD_RES_Set();
  delay(10);
  EPD_RES_Clr();
  delay(100);
  EPD_RES_Set();
  delay(100);
}

void EPD_Sleep(void) {
  EPD_WR_REG(0x07);
  EPD_WR_DATA8(0xA5);
  delay(20);
}

void EPD_Clear(void) {
  EPD_WR_REG(0x10);
  for (int i = 0; i < EPD_BUF_BYTES; i++) EPD_WR_DATA8(0xFF);
  EPD_WR_REG(0x13);
  for (int i = 0; i < EPD_BUF_BYTES; i++) EPD_WR_DATA8(0xFF);
  lut_GC();
}

void EPD_DisplayImage(const uint8_t* imageBW) {
  EPD_WR_REG(0x50);
  EPD_WR_DATA8(0xD7);
  EPD_WR_REG(0x13);
  for (int i = 0; i < EPD_BUF_BYTES; i++) EPD_WR_DATA8(imageBW[i]);
  lut_GC();
}

