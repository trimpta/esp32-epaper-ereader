void lut_GC(void) {
  uint8_t count;
  EPD_WR_REG(0x20);
  for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R20_GC[count]);
  EPD_WR_REG(0x21);
  for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R21_GC[count]);
  EPD_WR_REG(0x24);
  for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R24_GC[count]);
  if (lut_flag == 0) {
    EPD_WR_REG(0x22);
    for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R22_GC[count]);
    EPD_WR_REG(0x23);
    for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R23_GC[count]);
    lut_flag = 1;
  } else {
    EPD_WR_REG(0x23);
    for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R22_GC[count]);
    EPD_WR_REG(0x22);
    for (count = 0; count < 56; count++) EPD_WR_DATA8(lut_R23_GC[count]);
    lut_flag = 0;
  }
}

